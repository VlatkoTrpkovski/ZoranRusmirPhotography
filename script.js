// Load Dynamic Content from Firebase
// ============================================
async function loadDynamicGallery() {
    try {
        const snapshot = await db.collection('gallery').orderBy('createdAt', 'desc').get();
        if (snapshot.empty) return; // Keep static placeholders

        const galleryGrid = document.querySelector('.gallery-grid');
        galleryGrid.innerHTML = '';

        snapshot.forEach(doc => {
            const data = doc.data();
            const item = document.createElement('div');
            item.className = 'gallery-item ' + data.category;
            item.dataset.category = data.category;
            item.innerHTML = `
                <img src="${data.imageUrl}" alt="${data.title}" loading="lazy"
                     style="width:100%;height:100%;object-fit:cover;">
                <div class="gallery-overlay">
                    <h4>${data.title}</h4>
                    <p>${data.category.charAt(0).toUpperCase() + data.category.slice(1)}</p>
                </div>
            `;
            galleryGrid.appendChild(item);
        });

        setupLightbox();
        document.querySelectorAll('.gallery-item').forEach(el => {
            el.classList.add('fade-in');
            observer.observe(el);
        });
    } catch (err) {
        console.error('Error loading gallery from Firebase:', err);
    }
}

async function loadDynamicBlog() {
    try {
        const snapshot = await db.collection('posts').orderBy('createdAt', 'desc').get();
        if (snapshot.empty) return; // Keep static placeholders

        const blogGrid = document.querySelector('.blog-grid');
        blogGrid.innerHTML = '';

        snapshot.forEach(doc => {
            const data = doc.data();
            const card = document.createElement('article');
            card.className = 'blog-card';
            card.innerHTML = `
                ${data.coverImageUrl
                    ? `<img src="${data.coverImageUrl}" alt="${data.title}" loading="lazy" style="width:100%;height:200px;object-fit:cover;display:block;">`
                    : `<div class="blog-image-placeholder" style="background-color:#2a3a4a;"></div>`
                }
                <div class="blog-card-content">
                    <span class="blog-date">${data.date || ''}</span>
                    <h3>${data.title}</h3>
                    <p>${data.content.substring(0, 120)}${data.content.length > 120 ? '...' : ''}</p>
                </div>
            `;
            blogGrid.appendChild(card);
        });

        document.querySelectorAll('.blog-card').forEach(el => {
            el.classList.add('fade-in');
            observer.observe(el);
        });
    } catch (err) {
        console.error('Error loading blog from Firebase:', err);
    }
}

// Load dynamic content when Firebase is available
if (typeof db !== 'undefined') {
    loadDynamicGallery();
    loadDynamicBlog();
}
